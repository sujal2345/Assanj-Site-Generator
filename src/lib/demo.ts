/**
 * Preview saved websites with the complete demo presentation while keeping each
 * site's current business details and any non-empty generated content.
 */
export function createSitePreviewConfig(site: SiteConfig): SiteConfig {
  const demo = createDemoConfig();
  const hash = (site.id || site.slug || site.name).split("").reduce((value, char) => (value * 31 + char.charCodeAt(0)) >>> 0, 7);
  const pick = <T,>(items: T[], offset = 0) => items[(hash + offset) % items.length];

  const merge = (template: any, current: any): any => {
    if (Array.isArray(template)) {
      if (!Array.isArray(current) || current.length === 0) return template;
      return Array.from({ length: Math.max(template.length, current.length) }, (_, index) =>
        merge(template[index] ?? {}, current[index] ?? template[index] ?? {}),
      );
    }
    if (template && typeof template === "object") {
      const value = current && typeof current === "object" && !Array.isArray(current) ? current : {};
      return Object.fromEntries(Object.keys({ ...template, ...value }).map((key) => [key, merge(template[key], value[key])]));
    }
    if (typeof current === "string") return current.trim() ? current : (typeof template === "string" ? template : current);
    return current === undefined || current === null ? template : current;
  };

  const config = merge(demo, site) as SiteConfig;
  config.id = site.id;
  config.name = site.name;
  config.slug = site.slug;
  config.status = site.status;
  config.updatedAt = site.updatedAt;
  // Business details are authoritative, including intentionally empty contact fields.
  config.business = { ...site.business };
  config.business.name = site.business.name.trim() || site.name;
  config.business.tagline = site.business.tagline.trim() || pick([
    "Clean energy. Brighter possibilities.",
    "Powering a brighter, more sustainable future.",
    "Thoughtful solar solutions for a changing world.",
    "A smarter way to make every ray of sunshine count.",
    "Bringing reliable solar energy closer to home.",
  ]);
  config.business.description = site.business.description.trim() || pick([
    "We believe a brighter future starts with the energy choices we make today. Our team helps homes and businesses explore solar with clear guidance, thoughtful planning, and support at every step.",
    "Sunlight is full of possibility. We make the move to solar easier with practical advice, carefully planned systems, and a team ready to help from the first conversation onward.",
    "Good energy begins with a good plan. We work with each customer to understand their property, answer questions, and find a solar solution that feels right for their needs.",
    "Every property has its own potential. Our team brings together local knowledge and solar expertise to help customers take confident steps toward cleaner energy.",
    "Make more of the sunlight around you. From exploring your options to planning installation, we’re here to make your solar journey clear and welcoming.",
  ], 3);
  // Imported business metadata previously caused the site sections to hide all demo imagery.
  delete config.business.importSource;

  // Keep the demo's visual system and section composition consistent across previews.
  config.theme = demo.theme;
  config.layout = demo.layout;
  config.navigation = demo.navigation;
  config.navCta = demo.navCta;
  config.sectionOrder = demo.sectionOrder;
  config.sectionEnabled = demo.sectionEnabled;
  config.content.hero.layout = demo.content.hero.layout;
  config.content.hero.showForm = demo.content.hero.showForm;
  config.content.hero.trust = site.content.hero.trust;
  config.content.about.layout = demo.content.about.layout;
  config.content.about.calculator = site.content.about.calculator.enabled ? site.content.about.calculator : demo.content.about.calculator;
  if (!site.content.about.calculator.enabled) config.content.about.calculator.region = [site.business.city, site.business.state].filter(Boolean).join(", ");
  config.content.about.highlights = site.content.about.highlights;
  config.content.about.stats = site.content.about.stats;
  config.content.about.yearsExperience = site.content.about.yearsExperience;
  config.content.services.layout = demo.content.services.layout;
  config.content.testimonials.layout = demo.content.testimonials.layout;
  config.services = site.services;
  config.projects = site.projects;
  config.testimonials = site.testimonials;

  const replacements = ([
    ["SuryaShakti Solar", site.business.name || site.name],
    ["SuryaShakti", site.business.name || site.name],
    ["Pune", site.business.city],
    ["Maharashtra", site.business.state],
  ] as [string, string][]).filter(([, replacement]) => !!replacement);
  const replaceText = (value: any): any => {
    if (typeof value === "string") return replacements.reduce((text, [from, to]) => text.replaceAll(from, to), value);
    if (Array.isArray(value)) return value.map(replaceText);
    if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, replaceText(child)]));
    return value;
  };
  return replaceText(config) as SiteConfig;
}
